-- CB Diner schema for Supabase. Run it once in the SQL editor (or `supabase db push`),
-- then `npm run seed` to load the demo menu.

-- Staff --------------------------------------------------------------------
-- Create staff users in Authentication → Users, then add a row here:
--   insert into public.staff (user_id, name, role) values ('<auth user id>', 'Maria', 'admin');
create table if not exists public.staff (
  user_id uuid primary key references auth.users (id) on delete cascade,
  name text not null default '',
  role text not null default 'kitchen' check (role in ('kitchen', 'admin')),
  created_at timestamptz not null default now()
);

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid());
$$;

-- Menu ---------------------------------------------------------------------
create table if not exists public.categories (
  id text primary key,
  name text not null,
  blurb text not null default '',
  sort integer not null default 0
);

create table if not exists public.menu_items (
  id text primary key,
  category_id text not null references public.categories (id) on update cascade,
  name text not null,
  description text not null default '',
  price integer not null check (price > 0),          -- whole US dollars
  is_veg boolean not null default false,
  tags text[] not null default '{}',
  image_url text,
  thumb_url text,
  is_available boolean not null default true,
  sort integer not null default 0,
  updated_at timestamptz not null default now()
);
create index if not exists menu_items_category_idx on public.menu_items (category_id, sort);

-- Orders -------------------------------------------------------------------
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity (start with 1001) unique,
  table_no text,
  customer_name text,
  note text,
  lines jsonb not null,                               -- [{ itemId, name, price, qty, isVeg }]
  total integer not null check (total >= 0),
  status text not null default 'new' check (status in ('new', 'preparing', 'served', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists orders_created_idx on public.orders (created_at desc);

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists orders_touch on public.orders;
create trigger orders_touch before update on public.orders for each row execute function public.touch_updated_at();
drop trigger if exists menu_items_touch on public.menu_items;
create trigger menu_items_touch before update on public.menu_items for each row execute function public.touch_updated_at();

-- Row-level security ---------------------------------------------------------
-- The app writes through the service-role key on the server (after checking the
-- staff session), so browsers only get read access: the public menu, and the
-- order feed for signed-in staff (used by Realtime on the kitchen screen).
alter table public.staff enable row level security;
alter table public.categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.orders enable row level security;

drop policy if exists "staff read own row" on public.staff;
create policy "staff read own row" on public.staff for select to authenticated using (user_id = auth.uid());

drop policy if exists "menu is public" on public.categories;
create policy "menu is public" on public.categories for select using (true);
drop policy if exists "dishes are public" on public.menu_items;
create policy "dishes are public" on public.menu_items for select using (true);

drop policy if exists "staff read orders" on public.orders;
create policy "staff read orders" on public.orders for select to authenticated using (public.is_staff());

-- Realtime: stream order inserts/updates to the kitchen screen.
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'orders') then
    alter publication supabase_realtime add table public.orders;
  end if;
end $$;

